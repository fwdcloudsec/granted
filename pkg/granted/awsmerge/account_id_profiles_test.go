func TestProfileAccountAndRole(t *testing.T) {
	tests := []struct {
		name          string
		section       string
		wantAccountID string
		wantRoleName  string
	}{
		{
			name: "sso",
			section: `
sso_account_id = 123456789012
sso_role_name  = AdministratorAccess
`,
			wantAccountID: "123456789012",
			wantRoleName:  "AdministratorAccess",
		},
		{
			name: "granted_sso",
			section: `
granted_sso_account_id = 123456789012
granted_sso_role_name  = ReadOnly
credential_process     = granted credential-process --profile example
`,
			wantAccountID: "123456789012",
			wantRoleName:  "ReadOnly",
		},
		{
			name: "role_arn_with_path",
			section: `
role_arn       = arn:aws:iam::210987654321:role/team/Deploy
source_profile = base
`,
			wantAccountID: "210987654321",
			wantRoleName:  "Deploy",
		},
		{
			name: "role_arn_other_partition",
			section: `
role_arn = arn:aws-us-gov:iam::210987654321:role/Deploy
`,
			wantAccountID: "210987654321",
			wantRoleName:  "Deploy",
		},
		{
			name: "role_arn_takes_precedence",
			section: `
sso_account_id = 123456789012
sso_role_name  = AdministratorAccess
role_arn       = arn:aws:iam::210987654321:role/Deploy
`,
			wantAccountID: "210987654321",
			wantRoleName:  "Deploy",
		},
		{
			name: "invalid_account_id",
			section: `
sso_account_id = not-an-account
sso_role_name  = AdministratorAccess
`,
		},
		{
			name: "no_account",
			section: `
region = us-east-1
`,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			f, err := ini.Load([]byte("[profile example]\n" + tt.section))
			if err != nil {
				t.Fatal(err)
			}
			accountID, roleName := profileAccountAndRole(f.Section("profile example"))
			assert.Equal(t, tt.wantAccountID, accountID)
			assert.Equal(t, tt.wantRoleName, roleName)
		})
	}
}

